"""Shared neutral CEF TDB serialization for validated native interfaces."""
import copy
import re
import math


def _canonical_exponentials(expression):
    """Recover EXP after the reader/writer rounds Euler's constant to 15 digits.

    Only a numeric power base within floating serialization precision of e is
    canonicalized. Arbitrary nonintegral powers remain rejected by TCPrinter.
    """
    from symengine import Pow, RealDouble, E
    replacements = {}
    for power in expression.atoms(Pow):
        base, exponent = power.args
        if isinstance(base, RealDouble) and abs(float(base)-math.e) < 1e-14:
            replacements[power] = E**exponent
    return expression.xreplace(replacements)


def portable_tdb_text(db):
    """Export explicit CEF symmetry with phase-specific alphabetic type codes.

    Order/disorder mapping belongs only to the ordered phase declaration.
    Both TC 2026b and Pandat 2022 have been exercised on this representation.
    """
    db = copy.deepcopy(db)
    # Database.__deepcopy__ in pycalphad 0.11.1 only copies its parameter store.
    # Copy phase objects explicitly before changing their model hints.
    db.phases = copy.deepcopy(db.phases)
    for row in db._parameters.all():
        db._parameters.update({'parameter': _canonical_exponentials(row['parameter'])}, doc_ids=[row.doc_id])
    db.symbols = {name: _canonical_exponentials(value) for name, value in db.symbols.items()}
    for phase in db.phases.values():
        # The reader already generated symmetry-equivalent parameters. Without
        # this change the writer drops them and relies on :B/:F interpretation.
        for key in ("symmetry_BCC_4SL", "symmetry_FCC_4SL"):
            phase.model_hints.pop(key, None)
    text = db.to_string(fmt="tdb", groupby="phase", if_incompatible="raise")
    text = text.replace("DISORDERED_PART", "DISORDER_PART").replace("LOG(", "LN(")
    codes, lines = {}, []
    for line in text.splitlines():
        if line.startswith(("$ Date:", "$ Generated by")):
            continue
        match = re.match(r"TYPE_DEFINITION (\S+) GES AMEND_PHASE_DESCRIPTION (\w+) (DISORDER_PART|MAGNETIC) (.*)", line)
        if match:
            _, phase, kind, body = match.groups()
            index = sum(map(len, codes.values()))
            if index >= 26:
                raise ValueError("Too many type definitions for the Pandat adapter")
            code = chr(65+index)
            codes.setdefault(phase, []).append(code)
            line = f"TYPE_DEFINITION {code} GES AMEND_PHASE_DESCRIPTION {phase} {kind} {body}"
        match = re.match(r"PHASE (\S+) (\S+) (.*)", line)
        if match:
            phase, _, body = match.groups()
            # pycalphad's writer puts the ordering code on the reference too.
            # Pandat's native examples put it only on the ordered phase.
            line = f"PHASE {phase} %{''.join(codes.get(phase, []))} {body}"
        lines.append(line)
    text = "\n".join(lines)+"\n"
    # TC 2026b Education can silently omit VA when it encounters the vacancy
    # ELEMENT after three real elements (e.g. CO, TA, TI, VA). The ensuing
    # GET_DATA still reports success but excludes every VA-bearing phase.
    # Declare the existing pseudoelement before real elements. This is a pure
    # permutation: no element, constituent, coefficient or model is changed.
    vacancy = re.search(r"(?m)^ELEMENT\s+VA\s+[^!]+!\s*\n", text)
    if vacancy:
        declaration = vacancy.group(0)
        text = text[:vacancy.start()] + text[vacancy.end():]
        first_real = re.search(r"(?m)^ELEMENT\s+(?!/-\s)(?!VA\s)\S+\s", text)
        if first_real:
            text = text[:first_real.start()] + declaration + text[first_real.start():]
        else:
            text = declaration + text
    if db.symbols:
        function = re.compile(r"\b("+"|".join(re.escape(name) for name in sorted(db.symbols, key=len, reverse=True))+r")\b(?!#)")
        command = re.compile(r"((?:FUNCTION\s+\S+|PARAMETER\s+[^\n]*?\))\s+)([^!]+)", re.I)
        text = command.sub(lambda m: m[1]+function.sub(r"\1#", m[2]), text)
    # Appending explicit function markers above can take a line beyond the
    # native reader's80-column limit, even though pycalphad already wrapped
    # its original output. Reflow only after every compatibility rewrite.
    # pycalphad's token-aware formatter preserves exponents and expressions.
    from pycalphad.io.tdb import reflow_text
    from src.tdb_provenance import export_references
    return export_references(reflow_text(text, linewidth=78), db)
