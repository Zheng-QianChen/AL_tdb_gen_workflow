"""Prepare a traced single-phase TDB copy for Pandat 2022, without refitting.

The local calculation uses the original database. This adapter writes the
ordered phase and its reference with explicit symmetry parameters and portable
type codes. It is deliberately limited to the neutral CEF/IHJ models tested by
GibbsModel; it is not a general TDB dialect converter.
"""
import copy
import hashlib
import itertools
from pathlib import Path
import re

import numpy as np
from pycalphad import Database

from src.gibbs import GibbsModel, read_databases
from src.storage import atomic_json, atomic_write


def pandat_text(db):
    """Serialize expanded symmetry and use phase-specific alphabetic codes."""
    db = copy.deepcopy(db)
    # Database.__deepcopy__ in pycalphad 0.11.1 only copies its parameter store.
    # Copy phase objects explicitly before changing their model hints.
    db.phases = copy.deepcopy(db.phases)
    for phase in db.phases.values():
        # The reader already generated symmetry-equivalent parameters. Without
        # this change the writer drops them and relies on :B/:F interpretation.
        for key in ("symmetry_BCC_4SL", "symmetry_FCC_4SL"):
            phase.model_hints.pop(key, None)
    text = db.to_string(fmt="tdb", groupby="phase", if_incompatible="raise")
    text = text.replace("DISORDERED_PART", "DISORDER_PART").replace("LOG(", "LN(")
    codes, lines = {}, []
    for line in text.splitlines():
        if line.startswith(("$ Date:", "$ Generated by")):
            continue
        match = re.match(r"TYPE_DEFINITION (\S+) GES AMEND_PHASE_DESCRIPTION (\w+) (DISORDER_PART|MAGNETIC) (.*)", line)
        if match:
            _, phase, kind, body = match.groups()
            index = sum(map(len, codes.values()))
            if index >= 26:
                raise ValueError("Too many type definitions for the Pandat adapter")
            code = chr(65+index)
            codes.setdefault(phase, []).append(code)
            line = f"TYPE_DEFINITION {code} GES AMEND_PHASE_DESCRIPTION {phase} {kind} {body}"
        match = re.match(r"PHASE (\S+) (\S+) (.*)", line)
        if match:
            phase, _, body = match.groups()
            # pycalphad's writer puts the ordering code on the reference too.
            # Pandat's native examples put it only on the ordered phase.
            line = f"PHASE {phase} %{''.join(codes.get(phase, []))} {body}"
        lines.append(line)
    text = "\n".join(lines)+"\n"
    if db.symbols:
        function = re.compile(r"\b("+"|".join(re.escape(name) for name in sorted(db.symbols, key=len, reverse=True))+r")\b(?!#)")
        command = re.compile(r"((?:FUNCTION\s+\S+|PARAMETER\s+[^\n]*?\))\s+)([^!]+)", re.I)
        text = command.sub(lambda m: m[1]+function.sub(r"\1#", m[2]), text)
    return text


def phase_subset(original, phase):
    db = copy.deepcopy(original)
    phase = phase.upper()
    if phase not in db.phases:
        raise ValueError(f"Unknown phase {phase}")
    hints = db.phases[phase].model_hints
    kept = {phase}
    if hints.get("ordered_phase") == phase:
        kept.add(hints["disordered_phase"])
    db.phases = {name: value for name, value in db.phases.items() if name in kept}
    db._parameters.remove(doc_ids=[p.doc_id for p in db._parameters.all() if p["phase_name"] not in kept])
    used = set().union(*(set(group) for item in db.phases.values() for group in item.constituents))
    db.species = used
    db.elements = set().union(*(set(species.constituents) for species in used))
    return db


def equivalence(original, prepared, phase, temperatures, seed=20261018, samples=16):
    """Check G, TC, BMAG on random normalized sites and all ordered vertices.

    This tests the representation change, separately from the external solver.
    The original file remains the local model in the actual Pandat comparison.
    """
    models = [GibbsModel(db, phase, None, temperatures, 101325, True) for db in (original, prepared)]
    left, right = models
    if left.groups != right.groups or not np.array_equal(left.ratios, right.ratios) or left.ordering != right.ordering:
        raise ValueError("TDB conversion changed phase structure or ordering mapping")
    rng = np.random.default_rng(seed)
    points = [np.concatenate([rng.dirichlet(np.ones(len(group))) for group in left.groups]) for _ in range(samples)]
    for indices in itertools.product(*(range(len(group)) for group in left.groups)):
        points.append(np.concatenate([np.eye(len(group))[index] for group, index in zip(left.groups, indices)]))
    maximum = np.zeros(3)
    for temperature in temperatures:
        for y in points:
            values = [np.array([model.values(temperature, 101325, y)[0],
                                *model.magnetic_properties(temperature, 101325, *y)], dtype=float) for model in models]
            if not all(np.isfinite(value).all() for value in values):
                raise ValueError("Nonfinite TDB conversion audit")
            maximum = np.maximum(maximum, np.abs(values[0]-values[1]))
    if np.any(maximum > 1e-6):
        raise ValueError(f"TDB conversion changed G/TC/BMAG: {maximum}")
    return {"seed": seed, "states_per_temperature": len(points), "temperatures_K": temperatures,
            "max_abs_G_J_mol_atoms": maximum[0], "max_abs_TC_K": maximum[1], "max_abs_BMAG": maximum[2],
            "tolerance": 1e-6, "status": "passed"}


def prepare(source, phase, destination, temperatures):
    source, destination = Path(source), Path(destination)
    if source.resolve() == destination.resolve():
        raise ValueError("Keep the source TDB unchanged; choose a different destination")
    phase = phase.upper()
    original, _ = read_databases([str(source)])
    # Validate the supported model before serialization changes anything.
    GibbsModel(original, phase, None, temperatures, 101325, True)
    subset = phase_subset(original, phase)
    content = pandat_text(subset)
    prepared = Database(content.replace("DISORDER_PART", "DISORDERED_PART"))
    if len(prepared._parameters.all()) != len(subset._parameters.all()):
        raise ValueError("TDB conversion changed the number of selected parameters")
    audit = equivalence(original, prepared, phase, temperatures)
    atomic_write(destination, content)
    parameters = original._parameters.all()
    summary = {"source": str(source), "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
               "prepared": str(destination), "prepared_sha256": hashlib.sha256(destination.read_bytes()).hexdigest(),
               "phase": phase, "retained_phases": sorted(subset.phases),
               "source_selected_parameters": sum(p["phase_name"] in subset.phases for p in parameters),
               "prepared_parameters": len(prepared._parameters.all()),
               "ordered_magnetic_parameters": sum(p["phase_name"] == phase and p["parameter_type"] in {"TC", "BMAGN"} for p in parameters),
               "transformations": ["retain target and its disordered reference", "write symmetry-equivalent parameters explicitly",
                                   "use alphabetic type codes on the described phase", "DISORDER_PART keyword",
                                   "LN and explicit function-reference markers"], "equivalence": audit}
    atomic_json(destination.with_suffix(".conversion.json"), summary)
    return summary
